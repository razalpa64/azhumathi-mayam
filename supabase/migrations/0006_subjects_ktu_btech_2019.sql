-- ============================================================================
-- 0006 — Subjects: KTU B.Tech 2019 scheme (CSE, ECE, EEE, Civil)
-- ----------------------------------------------------------------------------
-- Source: APJ Abdul Kalam Technological University, B.Tech Curriculum 2019,
-- official branch curriculum tables (course code + title per semester).
-- Transcribed and cross-checked branch by branch; nothing invented.
--
-- Scope of this migration:
--   * S3-S8 for CSE, ECE, EEE and Civil Engineering: core subjects, labs,
--     comprehensive/project work and the full programme-elective baskets
--   * University-common subjects (EST/HUT/MCN) inserted once, shared by
--     every branch (specialization_id NULL)
--   * Deliberately excluded: Minor/Honours baskets and open electives -
--     those are separate enrolments or another department's subjects, and
--     listing them as branch subjects would mislead students
--   * S1/S2 keep the existing starter rows (the paired physics/chemistry
--     cycle subjects are college-assigned per group, so a single list
--     would be wrong for half the colleges)
--
-- Idempotent: a row is skipped when the same subject code already exists
-- for the same programme + semester + specialization + scheme (this also
-- means the originally seeded CSE starter subjects are preserved, never
-- duplicated). Requires 0001 (schema), the seed taxonomy (universities /
-- programmes / regulations) and 0005 (specializations) to be present;
-- on a live database all of those already are. Semesters are self-healed
-- below so the file is safe even on a partially seeded database.
-- ============================================================================

-- Semesters for B.Tech (normally created by the seed; harmless if present)
INSERT INTO public.semesters (programme_id, semester_number, label)
SELECT p.id, n, 'Semester ' || n
FROM public.programmes p
CROSS JOIN generate_series(1, p.total_semesters) AS n
WHERE p.code = 'BTECH'
ON CONFLICT (programme_id, semester_number) DO NOTHING;

