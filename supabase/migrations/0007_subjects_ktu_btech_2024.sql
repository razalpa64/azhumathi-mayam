-- Source: APJ Abdul Kalam Technological University, B.Tech Curriculum 2024,
-- official branch curriculum tables (course code + title per semester,
-- including the group-wise S1/S2 tables and every programme-elective
-- basket). Transcribed and cross-checked branch by branch from the
-- published curriculum; nothing invented.
--
-- Scope of this migration:
--   * S1-S8 for the nine branches above: core subjects, labs,
--     seminar/project work and the full programme-elective baskets
--   * S1/S2 attached per branch exactly as each branch's own published
--     table lists them (group codes genuinely differ between branches,
--     e.g. GYEST204 vs GXEST204) - no group table was generalised
--     across branches
--   * Physics/Chemistry and Health & Wellness / Life Skills are
--     either-or slots in S1 and S2; both coded options are listed in
--     both semesters, exactly as the curriculum tables present them
--     (students take one in S1 and the other in S2)
--   * The S7 HMC elective basket (UEHUT704 / UEHUM701-704) is
--     university-common, so it is inserted once as shared rows
--   * Deliberately excluded: Open / Industry-Linked Elective baskets
--     (university-wide choices, not a branch's own subjects) and
--     Minor/Honours/remedial slots - same rule as migration 0006
--
-- Idempotent: a row is skipped when the same subject code already
-- exists for the same programme + semester + specialization + scheme.
-- Requires 0001 (schema), the seed taxonomy and 0005
-- (specializations); semesters are self-healed below.
-- ============================================================================

-- Semesters for B.Tech (normally created by the seed; harmless if present)
INSERT INTO public.semesters (programme_id, semester_number, label)
SELECT p.id, n, 'Semester ' || n
FROM public.programmes p
CROSS JOIN generate_series(1, p.total_semesters) AS n
WHERE p.code = 'BTECH'
ON CONFLICT (programme_id, semester_number) DO NOTHING;

